inline bool HasHangulUtf8(const char* s) {
    if (!s) return false;
    const unsigned char* p = reinterpret_cast<const unsigned char*>(s);
    while (*p) {
        if (p[0] < 0x80) { ++p; continue; }
        if ((p[0] & 0xE0) == 0xC0) { p += p[1] ? 2 : 1; continue; }
        if ((p[0] & 0xF0) == 0xE0 && p[1] && p[2]) {
            const int cp = ((p[0] & 0x0F) << 12) | ((p[1] & 0x3F) << 6) | (p[2] & 0x3F);
            if (cp >= 0xAC00 && cp <= 0xD7A3) return true;
            p += 3; continue;
        }
        if ((p[0] & 0xF8) == 0xF0 && p[1] && p[2] && p[3]) { p += 4; continue; }
        ++p;
    }
    return false;
}

inline bool ReplaceAll(char* buf, size_t cap, const char* from, const char* to) {
    if (!buf || !from || !from[0]) return false;
    if (!to) to = "";
    const size_t fl = std::strlen(from);
    const size_t tl = std::strlen(to);
    bool any = false;
    for (;;) {
        char* p = std::strstr(buf, from);
        if (!p) break;
        const size_t prefix = static_cast<size_t>(p - buf);
        const size_t rest = std::strlen(p + fl);
        if (prefix + tl + rest + 1 > cap) break;
        std::memmove(p + tl, p + fl, rest + 1);
        if (tl) std::memcpy(p, to, tl);
        any = true;
    }
    return any;
}

