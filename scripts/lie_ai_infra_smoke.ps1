# 离线基建冒烟：写 fixture_echo 夹具并等待 ans（不依赖服端测谎）。
# 用法：
#   powershell -File scripts/lie_ai_infra_smoke.ps1
#   powershell -File scripts/lie_ai_infra_smoke.ps1 -BinDir "C:\path\to\bin\XCat_data"

param(
    [string]$BinDir = "",
    [int]$TimeoutSec = 20
)

$ErrorActionPreference = "Stop"

if (-not $BinDir) {
    $root = Split-Path -Parent $PSScriptRoot
    $BinDir = Join-Path $root "bin\XCat_data"
}

$req = Join-Path $BinDir "state\lie_ai\req"
$ans = Join-Path $BinDir "state\lie_ai\ans"
New-Item -ItemType Directory -Force -Path $req, $ans | Out-Null

$id = "lie_fix_{0:x8}" -f ([uint32](Get-Date).Ticks)
$txt = Join-Path $req "$id.txt"
$png = Join-Path $req "$id.png"
$ansFile = Join-Path $ans "$id.ans"

# ASCII-only body（兼容旧 PowerShell，避免 utf8NoBOM）
$body = "kind=fixture_echo`nq=offline fixture echo`no1=`no2=`no3=`no4=`n"
[System.IO.File]::WriteAllText($txt, $body)

[byte[]]$pngBytes = @(
    0x89,0x50,0x4E,0x47,0x0D,0x0A,0x1A,0x0A,0x00,0x00,0x00,0x0D,0x49,0x48,0x44,0x52,
    0x00,0x00,0x00,0x40,0x00,0x00,0x00,0x20,0x08,0x02,0x00,0x00,0x00,0x2D,0xFF,0xE9,
    0xD3,0x00,0x00,0x00,0x35,0x49,0x44,0x41,0x54,0x78,0xDA,0xED,0xCF,0x41,0x09,0x00,
    0x00,0x08,0x04,0xB0,0x8B,0x6F,0x6B,0x2F,0x83,0x4F,0x61,0xB0,0x02,0xCB,0x4E,0x5E,
    0x8B,0x80,0x80,0x80,0x80,0x80,0x80,0x80,0x80,0x80,0x80,0x80,0x80,0x80,0x80,0x80,
    0x80,0x80,0x80,0x80,0x80,0x80,0x80,0x80,0xC0,0x55,0x01,0x33,0xEC,0x38,0xB5,0x34,
    0x38,0x36,0x9A,0x00,0x00,0x00,0x00,0x49,0x45,0x4E,0x44,0xAE,0x42,0x60,0x82
)
[System.IO.File]::WriteAllBytes($png, $pngBytes)

Write-Host "Wrote fixture id=$id"
Write-Host "  txt=$txt"
Write-Host "Waiting for ans (need xcat.exe running LieAiPump_Tick)... timeout=${TimeoutSec}s"

$deadline = (Get-Date).AddSeconds($TimeoutSec)
while ((Get-Date) -lt $deadline) {
    if (Test-Path $ansFile) {
        Write-Host "PASS ans:"
        Get-Content $ansFile
        exit 0
    }
    Start-Sleep -Milliseconds 400
}

Write-Host "TIMEOUT: no ans. Ensure xcat.exe is running so LieAiPump picks up req/."
Write-Host "Or click panel button [本地泵] which also enqueues a fixture."
exit 1
