/**
 * XCAT 启动激活门 · 密钥对生成（产品=经典版 / TWMS）。
 *
 * 生成一把 ECDSA P-256 密钥对，供「个人 TOKEN」离线签发/验签：
 *   - 私钥  secrets/gate_ec_priv.pem      —— 你离线保管，永不随包发出（.gitignore）
 *   - 公钥  secrets/gate_ec_pub.pem       —— 更新服验签用（可提交，公钥非机密）
 *   - 公钥头 common/xcat_start_gate_secret.h —— 内嵌进 xcat.exe，离线验签用
 *
 * 只需跑一次；换一把密钥 = 老 TOKEN 全废 + 需重新发版（换公钥头）。
 *
 * 用法：
 *   node scripts/xcat-gate-keygen.mjs            # 若已存在私钥则拒绝覆盖
 *   node scripts/xcat-gate-keygen.mjs --force    # 强制重建（危险：作废所有已发 TOKEN）
 */
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");
const secretsDir = path.join(repoRoot, "secrets");
const privPath = path.join(secretsDir, "gate_ec_priv.pem");
const pubPath = path.join(secretsDir, "gate_ec_pub.pem");
const headerPath = path.join(repoRoot, "common", "xcat_start_gate_secret.h");

const force = process.argv.includes("--force");

if (fs.existsSync(privPath) && !force) {
  console.error(
    `[keygen] 已存在私钥 ${path.relative(repoRoot, privPath)}；不覆盖。\n` +
      `         重建会作废所有已发 TOKEN 且需换公钥重新发版；确需重建请加 --force。`,
  );
  process.exit(1);
}

const { publicKey, privateKey } = crypto.generateKeyPairSync("ec", {
  namedCurve: "prime256v1",
});

fs.mkdirSync(secretsDir, { recursive: true });
fs.writeFileSync(privPath, privateKey.export({ type: "pkcs8", format: "pem" }), "utf8");
fs.writeFileSync(pubPath, publicKey.export({ type: "spki", format: "pem" }), "utf8");

// 取原始公钥点 X||Y（各 32 字节），内嵌为 BCRYPT_ECCPUBLIC_BLOB 的坐标部分。
const jwk = publicKey.export({ format: "jwk" });
const x = Buffer.from(jwk.x, "base64url");
const y = Buffer.from(jwk.y, "base64url");
if (x.length !== 32 || y.length !== 32) {
  console.error(`[keygen] 意外的公钥坐标长度 x=${x.length} y=${y.length}`);
  process.exit(1);
}
const xy = Buffer.concat([x, y]);

const bytesToC = (buf) => {
  const lines = [];
  for (let i = 0; i < buf.length; i += 12) {
    const chunk = [...buf.slice(i, i + 12)].map((b) => `0x${b.toString(16).padStart(2, "0")}`);
    lines.push("    " + chunk.join(", ") + ",");
  }
  return lines.join("\n");
};

const header = `#pragma once
// AUTO-GENERATED by scripts/xcat-gate-keygen.mjs — DO NOT EDIT BY HAND.
// 内嵌 ECDSA P-256 公钥（原始点 X||Y，共 64 字节），用于启动激活 TOKEN 离线验签。
// 公钥非机密：拿到也只能验签、无法伪造 TOKEN（伪造需要 secrets/gate_ec_priv.pem 私钥）。
#include <cstdint>

namespace xcat {
namespace gate {

inline constexpr uint8_t kGatePubKeyXY[64] = {
${bytesToC(xy)}
};

}  // namespace gate
}  // namespace xcat
`;

fs.mkdirSync(path.dirname(headerPath), { recursive: true });
fs.writeFileSync(headerPath, header, "utf8");

console.log("[keygen] 已生成：");
console.log("  私钥（离线保管，勿提交）:", path.relative(repoRoot, privPath));
console.log("  公钥（服务端验签，可提交）:", path.relative(repoRoot, pubPath));
console.log("  公钥头（内嵌 exe，可提交）:", path.relative(repoRoot, headerPath));
console.log("\n下一步：node scripts/xcat-gate-sign.mjs --uid 张三 [--days 90]  给成员签 TOKEN。");
