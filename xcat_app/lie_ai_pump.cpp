void LieAiPump_Tick(const std::string& binDir) {
    if (binDir.empty()) return;
    EnsureWorkerStarted();

    const DWORD now = GetTickCount();
    RefreshConfigCached(binDir);
    RefreshPendingCached(binDir, now);

    LieAiConfig cfg{};
    bool workerBusy = false;
    bool hasResult  = false;
    JobResult result{};
    {
        std::lock_guard<std::mutex> lk(g_pump.mtx);
        g_pump.binDir = binDir;
        cfg           = g_pump.config;
        workerBusy    = g_pump.workerBusy;
        hasResult     = g_pump.hasResult;
        if (hasResult) {
            result           = g_pump.result;
            g_pump.hasResult = false;
        }
    }

    if (hasResult) {
        const std::string txtPath =
            (std::filesystem::path(ReqDir(binDir)) / (result.id + ".txt")).string();
        {
            std::lock_guard<std::mutex> lk(g_pump.mtx);
            if (result.ok) {
                std::string body;
                body += "ok=1\n";
                body += "kind=" + result.kind + "\n";
                body += "index=" + std::to_string(result.index) + "\n";
                body += "answer=" + result.answer + "\n";
                const std::string ansPath =
                    (std::filesystem::path(AnsDir(binDir)) / (result.id + ".ans")).string();
                if (WriteFileText(ansPath, body)) {
                    ++g_pump.sessionAnswered;
                    g_pump.lastError.clear();
                    xcat::log::Info("LieAI", "id=%s index=%d answer=%s", result.id.c_str(),
                                    result.index, result.answer.c_str());
                    char title[96]{};
                    char detail[192]{};
                    snprintf(title, sizeof(title), "测谎 AI 已答");
                    snprintf(detail, sizeof(detail), "%s → %s", result.id.c_str(),
                             result.answer.c_str());
                    xcat::app::notify::PushLocal(/*Success*/ 1, "lie-ai-ok", title, detail, 5000);
                    MoveReqPair(txtPath, DoneDir(binDir));
                } else {
                    g_pump.lastError = result.id + ": 写 ans 失败";
                    LogErrorThrottled(g_pump.lastError);
                    if (std::filesystem::exists(txtPath)) MoveReqPair(txtPath, FailedDir(binDir));
                }
            } else {
                g_pump.lastError = result.id + ": " + result.err;
                LogErrorThrottled(g_pump.lastError);
                xcat::app::notify::PushLocal(/*Warning*/ 2, "lie-ai-fail", "测谎 AI 失败",
                                             g_pump.lastError.c_str(), 6000);
                if (std::filesystem::exists(txtPath)) MoveReqPair(txtPath, FailedDir(binDir));
            }
        }
    }

    if (workerBusy) return;

    std::string txtPath;
    if (!cfg.enabled) {
        txtPath = PickNextFixtureEchoTxt(ReqDir(binDir));
    } else {
        txtPath = PickNextReqTxt(ReqDir(binDir));
    }
    if (txtPath.empty()) return;

    const std::string id = std::filesystem::path(txtPath).stem().string();
    {
        std::lock_guard<std::mutex> lk(g_pump.mtx);
        if (g_pump.hasJob || g_pump.workerBusy) return;
        if (!g_pump.activeId.empty() && g_pump.activeId == id) return;

        g_pump.job        = Job{binDir, txtPath, id, cfg};
        g_pump.hasJob     = true;
        g_pump.activeId   = id;
        g_pump.config     = cfg;
    }
    xcat::log::Info("LieAI", "quiz id=%s model=%s", id.c_str(), cfg.endpoint.model.c_str());
    g_pump.cv.notify_one();
}

void LieAiPump_Shutdown() {
    {
        std::lock_guard<std::mutex> lk(g_pump.mtx);
        g_pump.stop = true;
    }
    g_pump.cv.notify_all();
    if (g_pump.worker.joinable()) g_pump.worker.join();
}

LieAiPumpStats LieAiPump_GetStats() {
    LieAiPumpStats st{};
    std::lock_guard<std::mutex> lk(g_pump.mtx);
    st.pendingCount    = g_pump.pendingCount;
    st.sessionAnswered = g_pump.sessionAnswered;
    st.lastError       = g_pump.lastError;
    return st;
}

