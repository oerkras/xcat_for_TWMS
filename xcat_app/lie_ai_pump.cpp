std::string LieAiPump_EnqueueFixture(const std::string& binDir, bool echoOnly) {
    if (binDir.empty()) return {};
    EnsureDir(ReqDir(binDir));
    EnsureDir(AnsDir(binDir));
    EnsureDir(DoneDir(binDir));
    EnsureDir(FailedDir(binDir));

    char id[64]{};
    snprintf(id, sizeof(id), "lie_fix_%08lx", static_cast<unsigned long>(GetTickCount()));
    const std::string stem = ReqDir(binDir) + "\\" + id;
    const std::string txtPath = stem + ".txt";
    const std::string pngPath = stem + ".png";

    const std::string body =
        echoOnly
            ? "kind=fixture_echo\n"
              "q=offline fixture echo\n"
              "o1=\n"
              "o2=\n"
              "o3=\n"
              "o4=\n"
            : "kind=textcaptcha\n"
              "q=这是离线基建夹具。若无法识别图中文字，请只输出：FIXTURE\n"
              "o1=\n"
              "o2=\n"
              "o3=\n"
              "o4=\n";

    if (!WriteFileText(txtPath, body)) return {};
    {
        std::ofstream f(pngPath, std::ios::binary | std::ios::trunc);
        if (!f.is_open()) return {};
        f.write(reinterpret_cast<const char*>(kFixturePng), sizeof(kFixturePng));
        if (!f.good()) return {};
    }
    EnsureWorkerStarted();
    xcat::log::Info("LieAI", "fixture enqueued id=%s echo=%d", id, echoOnly ? 1 : 0);
    return std::string(id);
}

