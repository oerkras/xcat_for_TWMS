void EnsureDir(const std::string& path) {
    std::error_code ec;
    std::filesystem::create_directories(path, ec);
}

bool ReadFileBytes(const std::string& path, std::vector<uint8_t>& out) {
    std::ifstream f(path, std::ios::binary);
    if (!f.is_open()) return false;
    f.seekg(0, std::ios::end);
    const std::streamoff sz = f.tellg();
    if (sz <= 0) {
        out.clear();
        return true;
    }
    out.resize(static_cast<size_t>(sz));
    f.seekg(0, std::ios::beg);
    f.read(reinterpret_cast<char*>(out.data()), sz);
    return f.good() || f.eof();
}

bool ReadFileText(const std::string& path, std::string& out) {
    std::ifstream f(path, std::ios::binary);
    if (!f.is_open()) return false;
    out.assign(std::istreambuf_iterator<char>(f), std::istreambuf_iterator<char>());
    return true;
}

bool WriteFileText(const std::string& path, const std::string& text) {
    EnsureDir(std::filesystem::path(path).parent_path().string());
    std::ofstream f(path, std::ios::binary | std::ios::trunc);
    if (!f.is_open()) return false;
    f.write(text.data(), static_cast<std::streamsize>(text.size()));
    return f.good();
}

bool MoveReqPair(const std::string& txtPath, const std::string& destDir) {
    EnsureDir(destDir);
    namespace fs = std::filesystem;
    std::error_code ec;
    const fs::path txt(txtPath);
    const fs::path destTxt = fs::path(destDir) / txt.filename();

    auto moveOne = [](const fs::path& src, const fs::path& dest) -> bool {
        if (!fs::exists(src)) return true;
        std::error_code e;
        fs::rename(src, dest, e);
        if (!e) return true;
        fs::copy_file(src, dest, fs::copy_options::overwrite_existing, e);
        if (e) return false;
        fs::remove(src, e);
        return true;
    };

    bool ok = moveOne(txt, destTxt);
    for (const char* ext : {".png", ".bmp", ".jpg", ".jpeg"}) {
        const fs::path img = txt.parent_path() / (txt.stem().string() + ext);
        ok = moveOne(img, fs::path(destDir) / img.filename()) && ok;
    }
    return ok;
}

struct ProbeFields {
    std::string kind;
    std::string question;
    std::string ruid;
    std::vector<std::string> options;
};

std::string StripKey(const std::string& line, const char* key) {
    const size_t n = std::strlen(key);
    if (line.size() >= n && line.compare(0, n, key) == 0) return line.substr(n);
    return {};
}

bool ParseProbeTxt(const std::string& text, ProbeFields& out) {
    out = {};
    out.options.assign(4, std::string());
    std::string line;
    for (size_t i = 0; i <= text.size(); ++i) {
        if (i < text.size() && text[i] != '\n') {
            line.push_back(text[i]);
            continue;
        }
        if (!line.empty() && line.back() == '\r') line.pop_back();
        if (!line.empty()) {
            if (line.rfind("kind=", 0) == 0) out.kind = StripKey(line, "kind=");
            else if (line.rfind("q=", 0) == 0) out.question = StripKey(line, "q=");
            else if (line.rfind("ruid=", 0) == 0) out.ruid = StripKey(line, "ruid=");
            else if (line.rfind("o1=", 0) == 0) out.options[0] = StripKey(line, "o1=");
            else if (line.rfind("o2=", 0) == 0) out.options[1] = StripKey(line, "o2=");
            else if (line.rfind("o3=", 0) == 0) out.options[2] = StripKey(line, "o3=");
            else if (line.rfind("o4=", 0) == 0) out.options[3] = StripKey(line, "o4=");
        }
        line.clear();
    }
    if (out.kind == "textcaptcha" || out.kind == "captcha" || out.kind == "fixture_echo")
        return true;
    int nonempty = 0;
    for (const auto& o : out.options)
        if (!o.empty()) ++nonempty;
    return nonempty > 0;
}

int CountPendingTxt(const std::string& reqDir) {
    namespace fs = std::filesystem;
    std::error_code ec;
    if (!fs::exists(reqDir, ec)) return 0;
    int n = 0;
    for (const auto& ent : fs::directory_iterator(reqDir, ec)) {
        if (ec) break;
        if (!ent.is_regular_file()) continue;
        if (ent.path().extension() == ".txt") ++n;
    }
    return n;
}

std::string PickNextReqTxt(const std::string& reqDir) {
    namespace fs = std::filesystem;
    std::error_code ec;
    if (!fs::exists(reqDir, ec)) return {};
    std::string best;
    for (const auto& ent : fs::directory_iterator(reqDir, ec)) {
        if (ec) break;
        if (!ent.is_regular_file()) continue;
        const auto p = ent.path();
        if (p.extension() != ".txt") continue;
        const std::string s = p.string();
        if (best.empty() || s < best) best = s;
    }
    return best;
}

// 仅挑选 kind=fixture_echo（lie_ai.enabled=0 时用，避免被真题卡住）
std::string PickNextFixtureEchoTxt(const std::string& reqDir) {
    namespace fs = std::filesystem;
    std::error_code ec;
    if (!fs::exists(reqDir, ec)) return {};
    std::string best;
    for (const auto& ent : fs::directory_iterator(reqDir, ec)) {
        if (ec) break;
        if (!ent.is_regular_file()) continue;
        const auto p = ent.path();
        if (p.extension() != ".txt") continue;
        std::string body;
        ProbeFields fields;
        if (!ReadFileText(p.string(), body) || !ParseProbeTxt(body, fields)) continue;
        if (fields.kind != "fixture_echo") continue;
        const std::string s = p.string();
        if (best.empty() || s < best) best = s;
    }
    return best;
}

struct Job {
    std::string binDir;
    std::string txtPath;
    std::string id;
    LieAiConfig cfg;
};

struct JobResult {
    bool        ok = false;
    std::string id;
    std::string kind;
    int         index = 0;
    std::string answer;
    std::string err;
};

struct PumpState {
    std::mutex              mtx;
    std::condition_variable cv;
    std::thread             worker;
    bool                    stop       = false;
    bool                    workerBusy = false;
    bool                    hasJob     = false;
    bool                    hasResult  = false;
    Job                     job{};
    JobResult               result{};
    LieAiConfig             config{};
    std::string             binDir;
    int                     pendingCount    = 0;
    int                     sessionAnswered = 0;
    std::string             lastError;
    DWORD                   lastErrLogTick = 0;
    std::string             activeId;
    DWORD                   lastScanTick = 0;
    std::string             cfgBinDir;
    FILETIME                cfgIniMtime{};
    bool                    haveCfgIniMtime = false;
    bool                    cfgLoaded       = false;
};

PumpState g_pump;

void WorkerLoop() {
    for (;;) {
        Job job{};
        {
            std::unique_lock<std::mutex> lk(g_pump.mtx);
            g_pump.cv.wait(lk, [] { return g_pump.stop || g_pump.hasJob; });
            if (g_pump.stop && !g_pump.hasJob) break;
            job               = g_pump.job;
            g_pump.hasJob     = false;
            g_pump.workerBusy = true;
        }

        JobResult jr{};
        jr.id = job.id;

        std::string txt;
        ProbeFields fields;
        if (!ReadFileText(job.txtPath, txt) || !ParseProbeTxt(txt, fields)) {
            jr.ok  = false;
            jr.err = "解析题面失败";
        } else {
            jr.kind = fields.kind;
            // 优先干净 ruid PNG，再 jpg，再截屏 BMP。
            const std::filesystem::path stemPath =
                std::filesystem::path(job.txtPath).replace_extension("");
            std::vector<uint8_t> img;
            const char* mime = "image/bmp";
            const std::filesystem::path pngPath = std::filesystem::path(stemPath.string() + ".png");
            const std::filesystem::path jpgPath = std::filesystem::path(stemPath.string() + ".jpg");
            const std::filesystem::path jpegPath =
                std::filesystem::path(stemPath.string() + ".jpeg");
            const std::filesystem::path bmpPath = std::filesystem::path(stemPath.string() + ".bmp");
            if (std::filesystem::exists(pngPath) && ReadFileBytes(pngPath.string(), img) &&
                !img.empty()) {
                mime = "image/png";
            } else if (std::filesystem::exists(jpgPath) && ReadFileBytes(jpgPath.string(), img) &&
                       !img.empty()) {
                mime = "image/jpeg";
            } else if (std::filesystem::exists(jpegPath) && ReadFileBytes(jpegPath.string(), img) &&
                       !img.empty()) {
                mime = "image/jpeg";
            } else if (std::filesystem::exists(bmpPath)) {
                (void)ReadFileBytes(bmpPath.string(), img);
                mime = "image/bmp";
            }

            auto ep = job.cfg.endpoint;
            LlmResolveEndpoint(ep, LlmProviderKind::QwenVision);
            if (fields.kind == "fixture_echo") {
                jr.ok = true;
                jr.answer = "FIXTURE";
                jr.index = 1;
            } else if (fields.kind == "textcaptcha" || fields.kind == "captcha") {
                jr.ok = LlmOcrCaptcha(ep, img, mime, fields.question, jr.answer, jr.err);
                jr.index = jr.ok ? 1 : 0;
            } else {
                jr.ok = LlmAnswerQuiz(ep, img, mime, fields.question, fields.options, jr.index,
                                      jr.answer, jr.err);
                if (jr.ok && (jr.index < 1 || jr.index > 4 || jr.answer.empty())) {
                    jr.ok  = false;
                    jr.err = "模型返回无效选项";
                }
            }
        }

        {
            std::lock_guard<std::mutex> lk(g_pump.mtx);
            g_pump.result     = jr;
            g_pump.hasResult  = true;
            g_pump.workerBusy = false;
            g_pump.activeId.clear();
        }
        g_pump.cv.notify_one();
    }
}

void EnsureWorkerStarted() {
    if (g_pump.worker.joinable()) return;
    g_pump.worker = std::thread(WorkerLoop);
}

void LogErrorThrottled(const std::string& msg) {
    const DWORD now = GetTickCount();
    if (!msg.empty() && (g_pump.lastErrLogTick == 0 || now - g_pump.lastErrLogTick >= 5000)) {
        g_pump.lastErrLogTick = now;
        xcat::log::Warn("LieAI", "%s", msg.c_str());
    }
}

bool IniMtime(const std::string& binDir, FILETIME* out) {
    if (!out || binDir.empty()) return false;
    const std::string ini = xcat::UserConfigIniPath(binDir.c_str());
    HANDLE h = CreateFileA(ini.c_str(), GENERIC_READ, FILE_SHARE_READ | FILE_SHARE_WRITE, nullptr,
                           OPEN_EXISTING, FILE_ATTRIBUTE_NORMAL, nullptr);
    if (h == INVALID_HANDLE_VALUE) return false;
    const bool ok = GetFileTime(h, nullptr, nullptr, out) != 0;
    CloseHandle(h);
    return ok;
}

void RefreshConfigCached(const std::string& binDir) {
    FILETIME mtime{};
    const bool haveMtime = IniMtime(binDir, &mtime);
    if (g_pump.cfgBinDir == binDir && g_pump.cfgLoaded) {
        if (haveMtime && g_pump.haveCfgIniMtime && CompareFileTime(&mtime, &g_pump.cfgIniMtime) == 0)
            return;
        if (!haveMtime && !g_pump.haveCfgIniMtime) return;
    }
    LoadLieAiConfig(binDir, g_pump.config);
    g_pump.cfgBinDir = binDir;
    g_pump.cfgLoaded = true;
    if (haveMtime) {
        g_pump.cfgIniMtime     = mtime;
        g_pump.haveCfgIniMtime = true;
    } else {
        g_pump.haveCfgIniMtime = false;
    }
}

void RefreshPendingCached(const std::string& binDir, DWORD now) {
    if (g_pump.lastScanTick != 0 && now - g_pump.lastScanTick < 500) return;
    g_pump.lastScanTick = now;
    g_pump.pendingCount = CountPendingTxt(ReqDir(binDir));
}

